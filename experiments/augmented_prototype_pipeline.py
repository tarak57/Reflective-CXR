print("--- DEPLOYING MWV GENERATOR: SOFT RE-ALIGNMENT ---")

# 1. Custom Soft Penalty Logits Processor
class SoftPenaltyLogitsProcessor(LogitsProcessor):
    def __init__(self, penalty_token_ids, penalty_value=2.0):
        self.penalty_token_ids = penalty_token_ids
        self.penalty_value = penalty_value

    def __call__(self, input_ids, scores):
        for token_id in self.penalty_token_ids:
            scores[:, token_id] -= self.penalty_value
        return scores

def rescued_generate_safe_report(self, pixel_values):
    self.vlm_model.eval()

    # 2. LoRA Scaling (Attempting dynamic scale to 0.5)
    try:
        # Many PEFT versions allow setting the active adapter scale
        self.vlm_model.set_adapter("default", 0.5)
    except Exception:
        pass # If unsupported, the 0.7 temperature will act as our primary diversity driver

    force_prefix = "Findings:"
    decoder_input_ids = self.vlm_tokenizer(
        force_prefix,
        add_special_tokens=False,
        return_tensors="pt"
    ).input_ids.to(self.device)

    # Tokenize ONLY structural hallucination words for the soft penalty
    hallucination_words = ["hardware", "pacemaker", "tube", "catheter", "picc", "absent", "prosthesis"]
    penalty_ids = []
    for word in hallucination_words:
        tokens = self.vlm_tokenizer.encode(word, add_special_tokens=False)
        penalty_ids.extend(tokens)
    penalty_ids = list(set(penalty_ids))

    logits_processor = LogitsProcessorList([
        SoftPenaltyLogitsProcessor(penalty_token_ids=penalty_ids, penalty_value=2.0)
    ])

    with torch.no_grad():
        generated_ids = self.vlm_model.generate(
            pixel_values,
            decoder_input_ids=decoder_input_ids,
            max_length=60,
            do_sample=True,          # FIX 3: Enable probability sampling
            temperature=0.7,         # FIX 3: Controlled entropy
            top_p=0.9,               # FIX 3: Nucleus sampling
            top_k=50,                # FIX 3: Restrict extreme outliers
            logits_processor=logits_processor # FIX 1: Soft Penalty
        )

    report = self.vlm_tokenizer.decode(generated_ids[0], skip_special_tokens=True)
    report = report.replace("\n", " ").strip()

    # Restore LoRA scale for safety
    try:
        self.vlm_model.set_adapter("default", 1.0)
    except Exception:
        pass

    return report, 0

