class ReflectiveAgent:
    def __init__(self, model, tokenizer, processor, device):
        self.model = model
        self.tokenizer = tokenizer
        self.processor = processor
        self.device = device

        # The Critic's Knowledge Base: Phrases the AI is known to hallucinate on OOD data
        self.hallucination_triggers = [
            "foreign body",
            "density foreign body",
            "XXXX",
            "hardware",
            "sternotomy"
        ]

    def _clean_text(self, text):
        clean_text = re.sub(r'\(?\d+\s*images?\.?\)?', '', text, flags=re.IGNORECASE)
        clean_text = re.sub(r'\(?\d+\s*views?\.?\)?', '', clean_text, flags=re.IGNORECASE)
        clean_text = re.sub(r'\s+', ' ', clean_text).strip()
        return clean_text

    def draft_report(self, pixel_values, bad_words_ids=None):
        """Node 1 & 3: The Generator (First Pass and Rewrites)"""
        self.model.eval()
