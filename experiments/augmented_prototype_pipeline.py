# Define the Medical Augmentation Pipeline
medical_augmentations = transforms.Compose([
    transforms.RandomRotation(degrees=5),
    transforms.ColorJitter(contrast=0.2, brightness=0.1),
    transforms.RandomAffine(degrees=0, translate=(0.02, 0.02))
])

class IUXrayGenerativeDataset(Dataset):
    def __init__(self, dataframe, img_dir, tokenizer, processor, max_length=128, is_training=False):
        self.df = dataframe.reset_index(drop=True)
        self.img_dir = img_dir
        self.tokenizer = tokenizer
        self.processor = processor
        self.max_length = max_length
        self.is_training = is_training

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        img_name = self.df.loc[idx, 'filename']
        img_path = os.path.join(self.img_dir, 'images/images_normalized', img_name)

        try:
            image = Image.open(img_path).convert('RGB')
            # Only mutate if it is the training set
            if self.is_training:
                image = medical_augmentations(image)
        except Exception:
            image = Image.new('RGB', (224, 224), (0, 0, 0))

        pixel_values = self.processor(image, return_tensors="pt").pixel_values.squeeze()

        report_text = self.df.loc[idx, 'findings']
        encodings = self.tokenizer(
            report_text,
            padding="max_length",
            truncation=True,
            max_length=self.max_length,
            return_tensors="pt"
        )

        labels = encodings.input_ids.squeeze()
        labels[labels == self.tokenizer.pad_token_id] = -100

        return {"pixel_values": pixel_values, "labels": labels}

