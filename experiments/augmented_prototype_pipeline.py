def extract_clinical_labels(text, pathology):
    """
    Checks if a disease is present in the text AND ensures it is not negated.
    """
    # Ensure text is a string to prevent float errors on empty reports
    text = str(text).lower()

    # Find the disease
    match = re.search(r'\b' + pathology + r'\b', text)
    if match:
        # Check the 20 characters before the disease for negation words
        start = max(0, match.start() - 20)
        prefix = text[start:match.start()]
        negation_words = ['no ', 'without ', 'negative for ', 'clear of ', 'resolved ']
        if any(neg in prefix for neg in negation_words):
            return 0 # The disease is negated (Patient is healthy)
        return 1 # Positive finding (Patient is sick)
    return 0 # Not mentioned (Assume healthy/normal)

# Dictionaries to hold our binary labels (0 or 1)
