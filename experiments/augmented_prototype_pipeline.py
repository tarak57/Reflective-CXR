class HybridClinicalAgent:
    def __init__(self, agent_vlm, processor, device):
        self.agent = agent_vlm
        # We explicitly target the frozen Vision encoder inside your model
        self.vit_model = agent_vlm.vlm_model.get_encoder()
        self.processor = processor
        self.device = device

        # The Triage Templates
        self.normal_template = "Findings: The lungs are clear. No focal consolidation, pleural effusion, or pneumothorax is seen. Heart size and mediastinal contour are within normal limits. Visualized osseous structures are intact."
        self.uncertain_template = "Findings: Visual features are indeterminate. Subtle opacities cannot be excluded. Recommend clinical correlation or follow-up imaging."

    def extract_features(self, pixel_values):
        """Extracts the pure visual [CLS] token from the frozen ViT."""
        self.vit_model.eval()
        with torch.no_grad():
            outputs = self.vit_model(pixel_values=pixel_values)
            # Assuming standard ViT: batch, sequence, hidden_state. [:, 0, :] gets CLS token.
            features = outputs.last_hidden_state[:, 0, :]
        return features

    def heuristic_confidence(self, features):
        """Calculates normalized L2 norm as a proxy for feature activation/abnormality."""
        # Note: In a fully funded lab, this would be a trained Linear Probe.
        conf = torch.norm(features, dim=1)
        return conf

    def gated_generator(self, pixel_values):
        # 1. PERCEPTION (Independent)
        features = self.extract_features(pixel_values)
        raw_conf = self.heuristic_confidence(features)

        # Min-Max Normalization (using arbitrary bounds based on standard ViT outputs,
        # normally you would calibrate this over a validation set)
        conf_min, conf_max = 10.0, 50.0
        norm_conf = torch.clamp((raw_conf - conf_min) / (conf_max - conf_min + 1e-8), 0.0, 1.0).item()

        # 2. DECISION BOUNDARY (Triage)
        if norm_conf < 0.45:
            return self.normal_template, "Normal", norm_conf

        elif norm_conf > 0.75:
            # 3. GENERATION (Conditional Expert)
            report, _ = self.agent.generate_safe_report(pixel_values)
            return report, "Abnormal", norm_conf

        else:
            return self.uncertain_template, "Uncertain", norm_conf

